package animal;

import java.util.*;

public class Animal {
    private int age;
    private double weight;
    
    public Animal() {
        this.age = 0;
        this.weight = 0;
    }
    
    public Animal(int age, double weight) {
        this.age = age;
        this.weight = weight;
    }
}